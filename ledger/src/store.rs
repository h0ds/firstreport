//! The ledger on disk (plan §1): `sources.toml` plus one `claims/<id>.toml`
//! per outlet. Loaded whole; it is small. Written back per outlet so an
//! import touches only the files it changes.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::model::{validate_claim, Claim, Finding, Source};

#[derive(Debug, Default, Serialize, Deserialize)]
struct SourcesFile {
    #[serde(default, rename = "source")]
    sources: Vec<Source>,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct ClaimsFile {
    #[serde(default, rename = "claim")]
    claims: Vec<Claim>,
}

#[derive(Debug, Default, Clone)]
pub struct Ledger {
    pub sources: Vec<Source>,
    /// outlet id → claims, in file order.
    pub claims: BTreeMap<String, Vec<Claim>>,
}

#[derive(Debug)]
pub struct StoreError(pub String);
impl std::fmt::Display for StoreError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}
impl std::error::Error for StoreError {}

fn err<E: std::fmt::Display>(ctx: &str, e: E) -> StoreError {
    StoreError(format!("{ctx}: {e}"))
}

pub fn claims_dir(data_dir: &Path) -> PathBuf {
    data_dir.join("claims")
}

pub fn outlet_file(data_dir: &Path, outlet_id: &str) -> PathBuf {
    claims_dir(data_dir).join(format!("{outlet_id}.toml"))
}

pub fn load(data_dir: &Path) -> Result<Ledger, StoreError> {
    let sp = data_dir.join("sources.toml");
    let sources: SourcesFile = if sp.exists() {
        let t = std::fs::read_to_string(&sp).map_err(|e| err(&sp.display().to_string(), e))?;
        toml::from_str(&t).map_err(|e| err(&sp.display().to_string(), e))?
    } else {
        SourcesFile::default()
    };
    let mut claims = BTreeMap::new();
    let dir = claims_dir(data_dir);
    if dir.exists() {
        let mut entries: Vec<PathBuf> = std::fs::read_dir(&dir)
            .map_err(|e| err(&dir.display().to_string(), e))?
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().map(|x| x == "toml").unwrap_or(false))
            .collect();
        entries.sort();
        for p in entries {
            let id = p
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or_default()
                .to_string();
            let t = std::fs::read_to_string(&p).map_err(|e| err(&p.display().to_string(), e))?;
            let f: ClaimsFile = toml::from_str(&t).map_err(|e| err(&p.display().to_string(), e))?;
            for c in &f.claims {
                if c.outlet_id != id {
                    return Err(StoreError(format!(
                        "{}: claim for {:?} in the file for {:?}",
                        p.display(),
                        c.outlet_id,
                        id
                    )));
                }
            }
            claims.insert(id, f.claims);
        }
    }
    Ok(Ledger {
        sources: sources.sources,
        claims,
    })
}

/// Write one outlet's claims, replacing the file. Sorted by field then
/// source so diffs are stable.
pub fn write_outlet(
    data_dir: &Path,
    outlet_id: &str,
    mut claims: Vec<Claim>,
) -> Result<(), StoreError> {
    let dir = claims_dir(data_dir);
    std::fs::create_dir_all(&dir).map_err(|e| err(&dir.display().to_string(), e))?;
    claims.sort_by(|a, b| {
        (&a.field, &a.source_id, &a.value).cmp(&(&b.field, &b.source_id, &b.value))
    });
    let file = ClaimsFile { claims };
    let text = toml::to_string_pretty(&file).map_err(|e| err("serialize", e))?;
    let p = outlet_file(data_dir, outlet_id);
    let header = format!("# Claims about outlet {outlet_id:?}. One [[claim]] per fact, each with its source.\n# Generated by `ledger import`; hand edits are fine and survive re-import\n# unless they carry the re-imported source_id.\n\n");
    std::fs::write(&p, header + &text).map_err(|e| err(&p.display().to_string(), e))
}

/// Replace claims from `source_id` for one outlet with `fresh`, keeping
/// claims from every other source. Returns the merged set.
pub fn merge_source(existing: &[Claim], source_id: &str, fresh: Vec<Claim>) -> Vec<Claim> {
    let mut out: Vec<Claim> = existing
        .iter()
        .filter(|c| c.source_id != source_id)
        .cloned()
        .collect();
    out.extend(fresh);
    out
}

/// Feed's `outlets.toml`: only the ids are needed here.
#[derive(Debug, Deserialize)]
struct FeedOutlets {
    #[serde(default, rename = "outlet")]
    outlets: Vec<FeedOutlet>,
}

#[derive(Debug, Clone, Deserialize)]
pub struct FeedOutlet {
    pub id: String,
    #[serde(default)]
    pub name: String,
    #[serde(default)]
    pub domains: Vec<String>,
}

pub fn load_feed_outlets(path: &Path) -> Result<Vec<FeedOutlet>, StoreError> {
    let t = std::fs::read_to_string(path).map_err(|e| err(&path.display().to_string(), e))?;
    let f: FeedOutlets = toml::from_str(&t).map_err(|e| err(&path.display().to_string(), e))?;
    Ok(f.outlets)
}

/// Claims past their source's refresh interval: `(outlet, claim, age_days)`.
pub fn stale(ledger: &Ledger, now: i64) -> Vec<(String, Claim, i64)> {
    let mut out = Vec::new();
    for (id, claims) in &ledger.claims {
        for c in claims {
            if let Some(s) = ledger.sources.iter().find(|s| s.id == c.source_id) {
                if crate::model::is_stale(c, s, now) {
                    out.push((id.clone(), c.clone(), crate::model::age_days(c, now)));
                }
            }
        }
    }
    out
}

/// Sources that are due for re-import: scheduled, and either never
/// imported or holding at least one stale claim.
pub fn due_sources(ledger: &Ledger, now: i64) -> Vec<String> {
    ledger
        .sources
        .iter()
        .filter(|s| s.refresh_days > 0)
        .filter(|s| {
            let mine: Vec<&Claim> = ledger
                .claims
                .values()
                .flatten()
                .filter(|c| c.source_id == s.id)
                .collect();
            mine.is_empty() || mine.iter().any(|c| crate::model::is_stale(c, s, now))
        })
        .map(|s| s.id.clone())
        .collect()
}

/// Every finding across the ledger.
pub fn check(ledger: &Ledger, outlet_ids: Option<&[String]>) -> Vec<Finding> {
    let mut out = Vec::new();
    let mut seen = std::collections::HashSet::new();
    for s in &ledger.sources {
        if !seen.insert(s.id.clone()) {
            out.push(Finding::Error(format!("duplicate source id {:?}", s.id)));
        }
        if s.licence.trim().is_empty() {
            out.push(Finding::Error(format!("source {:?} has no licence", s.id)));
        }
    }
    for claims in ledger.claims.values() {
        for c in claims {
            out.extend(validate_claim(c, &ledger.sources, outlet_ids));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::SourceKind;

    fn tmp() -> PathBuf {
        let d = std::env::temp_dir().join(format!(
            "kg-ledger-{}-{}",
            std::process::id(),
            rand_suffix()
        ));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    fn rand_suffix() -> u64 {
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .subsec_nanos() as u64
    }

    fn claim(outlet: &str, field: &str, source: &str, value: &str) -> Claim {
        Claim {
            outlet_id: outlet.into(),
            field: field.into(),
            value: value.into(),
            data: None,
            source_id: source.into(),
            ref_url: "https://www.wikidata.org/wiki/Q9531".into(),
            retrieved_at: 1_700_000_000,
            as_of: None,
            note: None,
        }
    }

    #[test]
    fn roundtrip_and_merge() {
        let d = tmp();
        std::fs::write(
            d.join("sources.toml"),
            "[[source]]\nid = \"wikidata\"\nname = \"Wikidata\"\nurl = \"https://www.wikidata.org\"\nlicence = \"CC0-1.0\"\nkind = \"database\"\n",
        )
        .unwrap();
        write_outlet(
            &d,
            "bbc",
            vec![
                claim("bbc", "country", "wikidata", "United Kingdom"),
                claim("bbc", "bias", "allsides", "Center"),
            ],
        )
        .unwrap();
        let l = load(&d).unwrap();
        assert_eq!(l.sources.len(), 1);
        assert_eq!(l.sources[0].kind, SourceKind::Database);
        assert_eq!(l.claims["bbc"].len(), 2);
        assert_eq!(l.claims["bbc"][0].field, "bias", "sorted by field");

        let merged = merge_source(
            &l.claims["bbc"],
            "wikidata",
            vec![
                claim("bbc", "country", "wikidata", "UK"),
                claim("bbc", "founded", "wikidata", "1922"),
            ],
        );
        assert_eq!(merged.len(), 3);
        assert!(
            merged.iter().any(|c| c.source_id == "allsides"),
            "other sources kept"
        );
        assert!(
            merged.iter().any(|c| c.value == "UK"),
            "same source replaced"
        );

        let findings = check(&l, Some(&["bbc".into()]));
        assert!(findings
            .iter()
            .any(|f| f.to_string().contains("unknown source \"allsides\"")));
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn stale_and_due_follow_schedules() {
        let mut l = Ledger::default();
        l.sources.push(crate::model::Source {
            id: "wikidata".into(),
            name: "W".into(),
            url: String::new(),
            licence: "CC0-1.0".into(),
            kind: SourceKind::Database,
            notes: String::new(),
            no_redistribution: false,
            refresh_days: 0,
        });
        l.claims.insert(
            "bbc".into(),
            vec![claim("bbc", "country", "wikidata", "UK")],
        ); // retrieved 1_700_000_000
        let day = crate::model::SECS_PER_DAY;
        let now = 1_700_000_000 + 400 * day;
        assert!(stale(&l, now).is_empty(), "no schedule");
        assert!(due_sources(&l, now).is_empty());
        l.sources[0].refresh_days = 90;
        let st = stale(&l, now);
        assert_eq!(st.len(), 1);
        assert_eq!(st[0].2, 400);
        assert_eq!(due_sources(&l, now), vec!["wikidata"]);
        assert!(
            due_sources(&l, 1_700_000_000 + 10 * day).is_empty(),
            "fresh claims: not due"
        );
        l.claims.clear();
        assert_eq!(
            due_sources(&l, 1_700_000_000),
            vec!["wikidata"],
            "never imported: due"
        );
    }

    #[test]
    fn claim_in_wrong_file_is_rejected() {
        let d = tmp();
        write_outlet(&d, "bbc", vec![claim("cnn", "country", "wikidata", "US")]).unwrap();
        assert!(load(&d)
            .unwrap_err()
            .0
            .contains("claim for \"cnn\" in the file for \"bbc\""));
        let _ = std::fs::remove_dir_all(&d);
    }
}
